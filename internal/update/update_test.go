func TestParseLatestRedirect(t *testing.T) {
	base := mustURL(t, defaultReleaseBaseURL)
	tests := []struct {
		name     string
		location string
		want     string
		wantErr  bool
	}{
		{
			name:     "absolute",
			location: "https://github.com/Graphixa/FontGet/releases/tag/v1.2.3",
			want:     "1.2.3",
		},
		{
			name:     "relative",
			location: "/Graphixa/FontGet/releases/tag/v2.0.0",
			want:     "2.0.0",
		},
		{
			name:     "wrong host",
			location: "https://evil.example/Graphixa/FontGet/releases/tag/v1.2.3",
			wantErr:  true,
		},
		{
			name:     "wrong repository",
			location: "https://github.com/Someone/Else/releases/tag/v1.2.3",
			wantErr:  true,
		},
		{
			name:     "extra path",
			location: "https://github.com/Graphixa/FontGet/releases/tag/v1.2.3/extra",
			wantErr:  true,
		},
		{
			name:     "malformed semver",
			location: "https://github.com/Graphixa/FontGet/releases/tag/vlatest",
			wantErr:  true,
		},
		{
			name:     "query",
			location: "https://github.com/Graphixa/FontGet/releases/tag/v1.2.3?download=1",
			wantErr:  true,
		},
		{
			name:     "fragment",
			location: "https://github.com/Graphixa/FontGet/releases/tag/v1.2.3#release",
			wantErr:  true,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got, err := parseLatestRedirect(base, tc.location)
			if tc.wantErr {
				if err == nil {
					t.Fatalf("expected error, got %s", got)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if got.String() != tc.want {
				t.Fatalf("got %q, want %q", got, tc.want)
			}
		})
	}
}

