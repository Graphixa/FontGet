func TestUpdateToLatestUsesImmutableTaggedAssets(t *testing.T) {
	setTestPlatform(t, "linux", "amd64")
	setNoMigration(t)
	setVersion(t, "1.0.0")

	payload := []byte("updated-fontget")
	archive := mustTarGz(t, "fontget", payload)
	archiveName := "fontget_1.2.3_linux_amd64.tar.gz"
	checksums := checksumLine(archive, archiveName)

	var requests []string
	var authorizationSeen bool
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests = append(requests, r.URL.Path)
		authorizationSeen = authorizationSeen || r.Header.Get("Authorization") != ""
		switch r.URL.Path {
		case "/Graphixa/FontGet/releases/latest":
			http.Redirect(w, r, srv.URL+"/Graphixa/FontGet/releases/tag/v1.2.3", http.StatusFound)
		case "/Graphixa/FontGet/releases/download/v1.2.3/checksums.txt":
			_, _ = io.WriteString(w, checksums)
		case "/Graphixa/FontGet/releases/download/v1.2.3/" + archiveName:
			_, _ = w.Write(archive)
		default:
			http.NotFound(w, r)
		}
	}))
	defer srv.Close()
	setReleaseBase(t, srv.URL+"/Graphixa/FontGet/releases")

	dest := prepareExecutable(t, []byte("old"))
	if err := UpdateToLatest(); err != nil {
		t.Fatal(err)
	}
	assertFileContents(t, dest, payload)
	if authorizationSeen {
		t.Fatal("self-update requests must not include Authorization")
	}

	want := []string{
		"/Graphixa/FontGet/releases/latest",
		"/Graphixa/FontGet/releases/download/v1.2.3/checksums.txt",
		"/Graphixa/FontGet/releases/download/v1.2.3/" + archiveName,
	}
	if strings.Join(requests, "\n") != strings.Join(want, "\n") {
		t.Fatalf("requests:\n%v\nwant:\n%v", requests, want)
	}
}

