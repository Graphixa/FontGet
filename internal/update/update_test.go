func TestParseChecksums(t *testing.T) {
	const hash = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
	content := hash + "  fontget_1.2.3_linux_amd64.tar.gz\n" +
		strings.ToUpper(hash) + " *fontget_1.2.3_windows_amd64.zip\n" +
		"# generated by GoReleaser\n"

	sums, err := parseChecksums([]byte(content))
	if err != nil {
		t.Fatal(err)
	}
	if sums["fontget_1.2.3_linux_amd64.tar.gz"] != hash {
		t.Fatalf("linux hash = %q", sums["fontget_1.2.3_linux_amd64.tar.gz"])
	}
	if sums["fontget_1.2.3_windows_amd64.zip"] != hash {
		t.Fatalf("windows hash = %q", sums["fontget_1.2.3_windows_amd64.zip"])
	}
}

